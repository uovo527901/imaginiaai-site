export function galleryTextFields(work = {}, overrides = {}) {
  const fields = {};
  for (const [field, legacy] of [["title", "title"], ["description", "desc"]]) {
    for (const language of Object.keys(galleryLanguages)) {
      const key = `${field}_${language}`;
      fields[key] = overrides[key] ?? (language === "ko" ? overrides[legacy] : undefined)
        ?? work[key] ?? (language === "ko" ? work[legacy] : undefined) ?? "";
    }
  }
  return fields;
}

export function galleryWorkText(work, field, language) {
  const legacy = field === "title" ? "title" : "desc";
  return work[`${field}_${language}`]?.trim() || work[`${field}_ko`]?.trim() || work[legacy]?.trim() || "";
}

export function localizedGalleryWork(work, language) {
  return { ...work, title: galleryWorkText(work, "title", language), desc: galleryWorkText(work, "description", language) };
}

export function savedGalleryText(work, defaultDescription = "") {
  const fields = Object.fromEntries(Object.entries(galleryTextFields(work)).map(([field, value]) => [field, value.trim()]));
  fields.description_ko ||= defaultDescription || fields.title_ko;
  return { ...fields, title: fields.title_ko, desc: fields.description_ko };
}
